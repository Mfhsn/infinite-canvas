export type I18nKey = keyof typeof zh;
export type I18nTranslator = (key: I18nKey, params?: I18nParams) => string;

const messages: Record<AppLanguage, Record<I18nKey, string>> = {
    "zh-CN": zh,
    "en-US": en,
};

export function translate(language: AppLanguage, key: I18nKey, params?: I18nParams) {
    let text = messages[language][key];
    if (params) {
        for (const [name, value] of Object.entries(params)) {
            text = text.replaceAll(`{${name}}`, String(value));
        }
    }
    return text;
}
